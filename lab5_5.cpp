#include <iostream>
using namespace std;

// Рекурсивна функція для знаходження кількості одиниць у двійковому представленні n.
// n     - поточне число
// level - поточний рівень рекурсії
// depth - глибина рекурсії (максимальний досягнутий рівень, передається за посиланням)
int f(int n, int level, int &depth)
{
    // Оновлюємо глибину рекурсії, якщо поточний рівень більший
    if (level > depth)
        depth = level;

    // Виведення поточного рівня рекурсії
    cout << "Рівень рекурсії (level): " << level << ", n = " << n << endl;

    // Визначення кількосіт одиниць у двійковому представленні числа n
    if (n == 0)
        return 0;
    
    // Рекурентний виклик: f(n) = 1 + f(n & (n - 1)) + збільшення рівеня рекурсії 
    return 1 + f(n & (n - 1), level + 1, depth);
}

int main()
{
    int n;
    cout << "Введіть число n: ";
    cin >> n;

    if (n < 0)
    {
        cout << "Число n має бути невід'ємним!" << endl;
        return 1;
    }

    int depth = 0; // Змінна для збереження глибини рекурсії
    int ones = f(n, 1, depth); // Запуск рекурсії з 1-го рівня

    cout << "\n-----------------------------------" << endl;
    cout << "Кількість одиниць у двійковому коді: " << ones << endl;
    cout << "Глибина рекурсії (depth): " << depth << endl;
    cout << "-----------------------------------" << endl;

    return 0;
} 
